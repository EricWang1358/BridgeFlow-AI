import assert from 'node:assert/strict'

/** Real native sessions and persisted navigation. No model adapter is prompted. */
export async function notebookWalkthrough(page, scratch) {
  const top=page.locator('.bf-shell-top')
  const sources=page.getByRole('complementary',{name:'来源',exact:true})
  const studio=page.getByRole('complementary',{name:'工作室',exact:true})
  const title=top.getByRole('textbox',{name:'笔记本名称'})
  await page.locator('[contenteditable=true]').first().waitFor() // A notebook already belongs to BridgeFlow; no directory choice is needed.
  const saveDialog=page.getByRole('dialog',{name:'离开前保存笔记本？'})
  const history=page.getByRole('dialog',{name:'笔记本',exact:true})
  const toggle=top.getByRole('button',{name:'会话与设置',exact:true})
  for(let i=0;i<2;i++) {
    await toggle.click()
    await page.locator('[data-slot="sidebar"]').getByRole('button',{name:'收起侧边栏',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.bf-shell-top button:last-child')?.getAttribute('aria-expanded')==='false')
    assert.equal(await toggle.getAttribute('aria-expanded'),'false')
  }
  for(const label of ['来源','工作室']) {
    const button=top.getByRole('button',{name:label,exact:true})
    const on=await button.evaluate(el=>getComputedStyle(el).backgroundColor)
    await button.click()
    assert.equal(await button.getAttribute('aria-expanded'),'false')
    assert.notEqual(await button.evaluate(el=>getComputedStyle(el).backgroundColor),on)
    await button.click()
    assert.equal(await button.getAttribute('aria-expanded'),'true')
  }
  const resize=page.getByRole('separator',{name:'调整来源栏宽度'})
  const before=await sources.boundingBox(),handle=await resize.boundingBox()
  await page.mouse.move(handle.x+6,handle.y+120);await page.mouse.down();await page.mouse.move(handle.x-64,handle.y+120,{steps:8});await page.mouse.up()
  assert((await sources.boundingBox()).width < before.width-30)
  await resize.press('ArrowRight')
  const width=await sources.boundingBox()
  await title.fill('报价待办')
  await sources.getByRole('combobox',{name:'笔记本用途'}).selectOption('quotation')
  const state=studio.getByRole('button',{name:/业务状态/}).first()
  await state.click();await state.click()
  await studio.getByRole('region',{name:'报价进度'}).waitFor()
  assert.equal(await studio.getByRole('region',{name:'月度对账进度'}).count(),0)
  const quote=studio.getByRole('button',{name:/报价工作区/})
  await quote.click();await quote.click()
  assert.equal(await quote.getAttribute('aria-pressed'),'true')
  await studio.getByRole('main',{name:'报价',exact:true}).waitFor()
  await page.waitForFunction(()=>new URLSearchParams(location.hash.slice(12)).get('kind')==='quotation')

  await top.getByRole('button',{name:'保存笔记本',exact:true}).click()
  await top.getByText('已保存',{exact:true}).waitFor()
  await page.reload()
  await title.waitFor()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='报价待办')
  assert(Math.abs((await sources.boundingBox()).width-width.width)<2,'Panel width preference survives reload')
  await top.getByRole('button',{name:'新建笔记本',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='未命名笔记本')
  await title.fill('临时草稿')
  await top.getByRole('button',{name:'退出笔记本',exact:true}).click()
  await saveDialog.getByRole('button',{name:'取消，继续编辑'}).click()
  assert.equal(await title.inputValue(),'临时草稿')
  await top.getByRole('button',{name:'退出笔记本',exact:true}).click()
  await saveDialog.getByRole('button',{name:'不保存并继续'}).click()
  await history.getByRole('button',{name:/报价待办/}).waitFor()
  assert.equal(await history.getByRole('button',{name:/未命名笔记本/}).count(),0)
  await page.screenshot({path:`${scratch}/notebook-history.png`,fullPage:true})
  await history.getByRole('button',{name:/报价待办/}).click()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='报价待办')
  assert.equal(await sources.getByRole('combobox',{name:'笔记本用途'}).inputValue(),'quotation')
  await top.getByRole('button',{name:'笔记本',exact:true}).click()
  await history.getByRole('button',{name:'打开示例笔记本'}).click()
  await sources.getByRole('button',{name:/sample-production.csv/}).waitFor()
  assert.equal(await sources.locator('.bf-resource-list li').count(),4)
  await studio.locator('.bf-artifact[data-kind=master]').waitFor()
  assert.equal(await sources.getByRole('combobox',{name:'笔记本用途'}).inputValue(),'monthly')
  await sources.getByRole('button',{name:/sample-production.csv/}).click()
  await studio.getByRole('region',{name:'来源预览'}).waitFor()
  await title.fill('业务示例复核')
  await top.getByRole('button',{name:'新建笔记本',exact:true}).click()
  await page.screenshot({path:`${scratch}/notebook-save.png`,fullPage:true})
  // A failed save must keep the dialog and content; a retry commits the same notebook.
  await page.route('**/bridgeflow/notebook?*',async route=>{
    if(route.request().method()==='POST')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Save temporarily unavailable'})})
    else await route.continue()
  })
  await saveDialog.getByRole('button',{name:'保存并继续',exact:true}).click()
  await saveDialog.getByRole('alert').waitFor()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='业务示例复核')
  await page.unroute('**/bridgeflow/notebook?*')
  await saveDialog.getByRole('button',{name:'保存并继续',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='未命名笔记本')
  assert.equal(await sources.locator('.bf-resource-list li').count(),0)
  await top.getByRole('button',{name:'笔记本',exact:true}).click()
  await history.getByRole('button',{name:/业务示例复核/}).click()
  await sources.getByRole('button',{name:/sample-production.csv/}).waitFor()
  await studio.getByRole('region',{name:'来源预览'}).waitFor()
  await page.reload()
  await sources.getByRole('button',{name:/sample-production.csv/}).waitFor()
  await studio.getByRole('region',{name:'来源预览'}).waitFor()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='业务示例复核')
  await top.getByRole('button',{name:'退出笔记本',exact:true}).click()
  await history.getByRole('button',{name:/业务示例复核/}).click()
  await sources.getByRole('button',{name:/sample-production.csv/}).waitFor()
  await studio.getByRole('region',{name:'来源预览'}).waitFor()
  await page.waitForFunction(()=>document.querySelector('.bf-notebook-title')?.value==='业务示例复核')
  await page.locator('[contenteditable=true]').first().waitFor()
  await page.screenshot({path:`${scratch}/notebook-sample.png`,fullPage:true})
  await page.setViewportSize({width:390,height:844})
  assert(await top.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Mobile header must not overflow')
  await top.getByRole('button',{name:'工作室',exact:true}).click()
  await top.getByRole('button',{name:'来源',exact:true}).click()
  assert.equal(await top.getByRole('button',{name:'来源',exact:true}).getAttribute('aria-expanded'),'true')
  await page.setViewportSize({width:1440,height:1000})
}
